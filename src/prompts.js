export function randomPrompt(tag) {
  const pools = {
    mood: PROMPTS.slice(0, 14),
    insight: PROMPTS.slice(14, 28),
    challenge: PROMPTS.slice(28, 40),
    win: PROMPTS.slice(40, 52)
  };
  const pool = (tag && pools[tag]) || PROMPTS;
  return pool[Math.floor(Math.random() * pool.length)];
}
